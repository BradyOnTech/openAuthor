import { test } from "@e2e-dev/web";
import { expect } from "e2e";
import { desktopBook } from "../support/desktopBook.ts";

test("desktop writes and plans a book, reviews a revision, undoes it and refuses a stale save", { tags: ["desktop", "authoring", "writing-safety"], timeout: 150_000 }, async ({ app, browser, screen }) => {
  const book = await desktopBook(browser);
  try {
    await app.open("/");
    await screen.getByRole("button", "New Project").tap();
    await screen.getByRole("textbox", "Novel title").fill("The Lantern Cartographer");
    await screen.getByRole("textbox", "Project folder").fill(book.projectRoot);
    await screen.getByRole("button", "Create novel").tap();
    await screen.getByPlaceholder("New scene title...").fill("The Moving Map");
    await screen.getByRole("button", "Add Scene").tap();
    const prose = screen.getByRole("textbox", "Scene prose");
    const original = "Mara unrolled the map beside the lamp. A red line crept across the paper, passing streets the city had forgotten. She locked the door and watched it move.\n\nAt midnight, the line reached her own door.";
    await prose.fill(original);
    await prose.press("Control+Shift+Z");
    await expect(screen.getByRole("button", "Exit focus mode")).toBeVisible();
    await prose.press("Escape");
    await prose.press("Control+s");
    await expect(screen.getByText("Saved")).toBeVisible();
    await screen.getByRole("button", "Hide first-run guide").tap();

    await screen.getByRole("button", /^Plan \(/).tap();
    await screen.getByRole("textbox", "Synopsis").fill("A living map chooses Mara's door.");
    await screen.getByRole("textbox", "Genre").fill("Fantasy mystery");
    await screen.getByRole("button", "Save Brief").tap();
    await expect(screen.getByText("Project brief saved.")).toBeVisible();
    await screen.getByPlaceholder("New act title").fill("The Lost Hour");
    await screen.getByRole("button", "Add Act").tap();
    await screen.getByPlaceholder("Chapter title").fill("The Summons");
    await screen.getByRole("button", "Add").tap();
    await screen.getByRole("combobox", "Move The Moving Map to").selectOption({ label: "The Lost Hour · The Summons" });
    await screen.getByRole("button", "Move The Moving Map").tap();
    await screen.getByRole("textbox", "New beat for The Moving Map").fill("The map chooses Mara's door.");
    await screen.getByRole("button", "Add beat to The Moving Map").tap();
    await expect(screen.getByText("Beat 1: The map chooses Mara's door.")).toBeVisible();
    const plan = await book.json(["plan", "get"]);
    expect(plan.brief.synopsis).toBe("A living map chooses Mara's door.");
    expect(plan.beats).toHaveLength(1);
    await screen.getByRole("button", /^Manuscript \(/).tap();
    await screen.getByRole("button", "Read manuscript").tap();
    await expect(screen.getByRole("main", "Manuscript reading copy")).toContainText("At midnight, the line reached her own door.");

    const setup = "The map has chosen Mara's door.";
    await book.json(["memory", "setup-add", "--description", setup, "--scene", "scene-0001", "--excerpt", "At midnight, the line reached her own door."]);
    await screen.getByRole("button", /^Changes \(/).tap();
    await screen.getByRole("button", /^Plan brief author_edit/).tap();
    await expect(screen.getByText("Revision retrospective")).toBeVisible();
    await expect(screen.getByText("manuscript/structure.json")).toBeVisible();
    await expect(screen.getByText(/\+.*"synopsis": "A living map chooses Mara's door\."/)).toBeVisible();
    await screen.getByRole("button", /^Memory setup-add author_edit/).tap();
    await expect(screen.getByText("codex/memory.json")).toBeVisible();
    await expect(screen.getByText(/\+.*"description": "The map has chosen Mara's door\."/)).toBeVisible();
    await expect(screen.getByText(`• ${setup}`)).toBeVisible();
    await screen.getByRole("button", "+ AI").tap();
    await screen.getByRole("textbox", "What should change?").fill("Make the final paragraph more ominous while preserving all names, facts, and events.");
    await screen.getByRole("combobox", "Provider").selectOption("local");
    await screen.getByRole("button", "Create Change Set").tap();
    await screen.getByRole("button", "Generate reviewed edit plan").tap();
    await screen.getByRole("button", "Generate reviewed scene").tap();
    expect((await book.json(["scene", "get", "--id", "scene-0001"])).body.trimEnd()).toBe(original);
    await screen.getByRole("button", "Apply 1 change").tap();
    await expect(screen.getByRole("button", "Undo change")).toBeVisible();
    expect((await book.json(["scene", "get", "--id", "scene-0001"])).body.trimEnd()).toBe(original.replace("reached her own door", "found her own door"));
    await screen.getByRole("button", /^Apply proposal-/).tap();
    await expect(screen.getByRole("heading", "1 scene changed; +0 words; 1 accepted Change Hunk.")).toBeVisible();
    await expect(screen.getByText("Goal: Make the final paragraph more ominous while preserving all names, facts, and events.")).toBeVisible();
    await expect(screen.getByText("+0 words")).toBeVisible();
    await expect(screen.getByText(/\+At midnight, the line found her own door\./)).toBeVisible();
    await screen.getByRole("button", /— applied$/).tap();
    await screen.getByRole("button", "Undo change").tap();
    await expect(screen.getByRole("status").filter({ hasText: "Change undone" })).toBeVisible();
    await screen.getByRole("textbox", "Version name").fill("After reviewing the map");
    await screen.getByRole("button", "Save version").tap();
    const savedVersion = screen.getByRole("button", /^After reviewing the map/);
    await expect(savedVersion).toBeVisible();
    await savedVersion.tap();
    await expect(screen.getByText("Revision retrospective")).toBeVisible();
    await expect(screen.getByRole("button", "Restore this scene")).toBeVisible();
    const laterVersion = "Mara opened the map case beside a door that had vanished.";
    await book.json(["scene", "update", "--id", "scene-0001", "--body", laterVersion]);
    expect((await book.json(["scene", "get", "--id", "scene-0001"])).body.trimEnd()).toBe(laterVersion);
    const revisionCount = (await book.json(["revision", "list"])).length;
    await screen.getByRole("button", "Restore this scene").tap();
    await expect(screen.getByRole("status").filter({ hasText: "as a new Revision" })).toBeVisible();
    expect((await book.json(["revision", "list"])).length).toBe(revisionCount + 1);
    expect((await book.json(["scene", "get", "--id", "scene-0001"])).body.trimEnd()).toBe(original);
    await screen.getByRole("button", /^Manuscript \(/).tap();
    await screen.getByRole("navigation", "Manuscript scenes").getByRole("button", /The Moving Map DRA/).tap();
    await expect(prose).toHaveValue(original + "\n");
    await browser.reload();
    await expect(prose).toHaveValue(original + "\n");

    const savedElsewhere = "Mara followed the line to a door that had never existed.";
    await book.json(["scene", "update", "--id", "scene-0001", "--body", savedElsewhere]);
    const localDraft = "Mara hid the moving map beneath the floorboards.";
    await prose.fill(localDraft);
    await prose.press("Control+s");
    await expect(screen.getByRole("heading", "Scene changed elsewhere")).toBeVisible();
    expect((await book.json(["scene", "get", "--id", "scene-0001"])).body.trimEnd()).toBe(savedElsewhere);
    await browser.reload();
    await screen.getByRole("button", "Restore").tap();
    await expect(prose).toHaveValue(localDraft);
    await prose.press("Control+s");
    await expect(screen.getByRole("heading", "Scene changed elsewhere")).toBeVisible();
    await prose.fill("Mara hid the map, then followed its line to the impossible door.");
    await screen.getByRole("button", "Save reconciled version").tap();
    await expect(screen.getByText("Saved")).toBeVisible();
    expect((await book.json(["scene", "get", "--id", "scene-0001"])).body.trimEnd()).toBe("Mara hid the map, then followed its line to the impossible door.");
    expect(await book.errors()).toEqual([]);
  } finally { await book.close(); }
});
