import { test } from "@e2e-dev/web";
import { expect } from "e2e";
import { desktopBook } from "../support/desktopBook.ts";

test("desktop branches a Storyline, reviews a conflict and merges the approved reconciliation", { tags: ["desktop", "merge", "storylines"], timeout: 150_000 }, async ({ app, browser, screen }) => {
  const book = await desktopBook(browser);
  try {
    await app.open("/");
    await screen.getByRole("button", "New Project").tap();
    await screen.getByRole("textbox", "Novel title").fill("The Lantern Cartographer");
    await screen.getByRole("textbox", "Project folder").fill(book.projectRoot);
    await screen.getByRole("button", "Create novel").tap();
    await expect(screen.getByRole("button", "Add Scene")).toBeVisible();
    await screen.getByRole("button", "Hide first-run guide").tap();
    await book.json(["scene", "add", "--title", "The Gate", "--body", "Mara closed the gate before dawn."]);
    await book.json(["plan", "get"]);
    expect((await book.core(book.projectRoot, ["snapshot", "create", "--message", "The first ending"])).status).toBe(0);
    const primary = (await book.json(["branch", "list"])).find((row: { current: boolean }) => row.current).name;
    await browser.reload();
    await browser.keyboard.press("Control+j");
    await screen.getByRole("tablist", "Project tools").getByRole("tab", "Merge").tap();
    const merge = screen.getByRole("tabpanel", "Merge");
    await merge.getByRole("textbox", "New storyline name").fill("gate-open");
    await merge.getByRole("button", "Branch storyline").tap();
    await expect(merge.getByText("gate-open (current)")).toBeVisible();
    await expect(screen.getByRole("status").filter({ hasText: "Created storyline" })).toBeVisible();
    await screen.getByRole("navigation", "Manuscript scenes").getByRole("button", "The Gate DRA").tap();
    const prose = screen.getByRole("textbox", "Scene prose");
    await prose.fill("Mara left the gate open for Ivo.");
    await prose.press("Control+s");
    await expect(screen.getByText("Saved")).toBeVisible();
    expect((await book.core(book.projectRoot, ["snapshot", "create", "--message", "Keep the gate open"])).status).toBe(0);
    const switchPrimary = merge.getByRole("button", `Switch to ${primary}`);
    await switchPrimary.focus();
    await switchPrimary.press("Enter");
    await expect(merge.getByText(`${primary} (current)`)).toBeVisible();
    await expect(screen.getByRole("status").filter({ hasText: "Switched to storyline" })).toBeVisible();
    await screen.getByRole("navigation", "Manuscript scenes").getByRole("button", "The Gate DRA").tap();
    await expect(prose).toHaveValue("Mara closed the gate before dawn.\n");
    await prose.fill("Mara chained the gate shut before dawn.");
    await prose.press("Control+s");
    await expect(screen.getByText("Saved")).toBeVisible();
    expect((await book.core(book.projectRoot, ["snapshot", "create", "--message", "Chain the gate"])).status).toBe(0);
    await merge.getByRole("combobox", "Storyline to merge").selectOption({ value: "gate-open" });
    await merge.getByRole("combobox", "Destination storyline").selectOption({ value: primary });
    await merge.getByRole("button", "Check compatibility").tap();
    await expect(merge.getByText("1 scene conflict")).toBeVisible();
    await expect(merge.getByRole("button", "Merge storyline")).toBeDisabled();
    await merge.getByRole("button", "Reconcile with AI").tap();
    const context = merge.getByRole("region", "Review reconciliation context");
    await expect(context).toContainText("The Gate");
    await context.getByRole("button", "Generate reviewed reconciliation").tap();
    await expect(merge.getByText("reconciled")).toBeVisible();
    expect((await book.json(["scene", "get", "--id", "scene-0001"])).body.trimEnd()).toBe("Mara chained the gate shut before dawn.");
    await merge.getByRole("button", "Merge with 1 reconciliation").tap();
    await expect(merge.getByText(new RegExp(`Merged gate-open into ${primary}`))).toBeVisible();
    const result = await book.json(["scene", "get", "--id", "scene-0001"]);
    expect(result.body).toContain("Mara chained the gate shut before dawn.");
    expect(result.body).toContain("Mara left the gate open for Ivo.");
    expect((await book.json(["branch", "list"])).find((row: { current: boolean }) => row.current).name).toBe(primary);
    expect(await book.errors()).toEqual([]);
  } finally { await book.close(); }
});
